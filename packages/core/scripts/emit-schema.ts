// Emits packages/core/schema/jobs.schema.json from the zod contract (ADR 0004).
import { writeFileSync, mkdirSync } from "node:fs";
import { z } from "zod";
import { JOB_SPECS, CONTRACT, ClaimedJob } from "../src/jobs";

const jobs: Record<string, unknown> = {};
for (const [type, spec] of Object.entries(JOB_SPECS)) {
  jobs[type] = {
    version: spec.version,
    input: z.toJSONSchema(spec.input, { io: "input" }),
    output: z.toJSONSchema(spec.output, { io: "output" }),
  };
}
const doc = {
  $comment: "GENERATED by packages/core/scripts/emit-schema.ts — do not edit",
  contract: CONTRACT,
  envelope: z.toJSONSchema(ClaimedJob),
  jobs,
};
const out = new URL("../schema/jobs.schema.json", import.meta.url);
mkdirSync(new URL("../schema/", import.meta.url), { recursive: true });
writeFileSync(out, JSON.stringify(doc, null, 2) + "\n");
console.log(`wrote ${out.pathname} (${Object.keys(jobs).length} job types)`);
