// Writes packages/core/test/fixtures/autocut-cases.json: the TS autocut's output on the shared cases. The Python
// handler's tests (services/engine/tests/test_autocut.py) must reproduce every case exactly.
import { writeFileSync } from "node:fs";
import { autocut } from "../src/autocut";
import { NAMED, randomCases } from "../test/fixtures/autocutCases";

const cases = [...NAMED, ...randomCases(60)].map((c) => ({ ...c, output: autocut(c.input) }));
const out = new URL("../test/fixtures/autocut-cases.json", import.meta.url);
writeFileSync(out, JSON.stringify({ $comment: "GENERATED by packages/core/scripts/emit-autocut-fixtures.ts — do not edit", cases }, null, 1) + "\n");
console.log(`wrote ${cases.length} cases`);
