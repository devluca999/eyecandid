/**
 * Generate tokens from the Claude Design export (design/tokens/*.css). Never hand-edit the outputs.
 *   src/tokens.css            → the design CSS verbatim (web imports this; liquid glass, springs, keyframes intact)
 *   src/theme.css             → Tailwind v4 @theme mapping utilities onto the CSS variables
 *   src/tokens.generated.ts   → resolved values for React Native (Paper + Night), and for tests
 */
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../../../design/tokens/", import.meta.url);
const files = ["fonts.css", "colors.css", "typography.css", "layout.css", "effects.css"];
const css = Object.fromEntries(files.map((f) => [f, readFileSync(new URL(f, root), "utf8")]));

type Vars = Record<string, string>;
function block(src: string, selector: string): Vars {
  const out: Vars = {};
  const re = new RegExp(`${selector.replace(/[[\]"=]/g, "\\$&")}\\s*\\{([^}]*)\\}`, "g");
  for (const m of src.matchAll(re)) {
    const body = m[1]!.replace(/\/\*[\s\S]*?\*\//g, "");
    for (const d of body.split(";")) {
      const i = d.indexOf(":");
      if (i < 0) continue;
      const k = d.slice(0, i).trim();
      if (k.startsWith("--")) out[k.slice(2)] = d.slice(i + 1).trim();
    }
  }
  return out;
}

const all = Object.values(css).join("\n");
const paper: Vars = block(all, ":root");
const nightOverrides: Vars = block(all, '[data-theme="night"]');
const night: Vars = { ...paper, ...nightOverrides };

function resolve(vars: Vars, v: string, depth = 0): string {
  if (depth > 10) return v;
  return v.replace(/var\(--([\w-]+)\)/g, (_, k: string) => (vars[k] !== undefined ? resolve(vars, vars[k]!, depth + 1) : `var(--${k})`));
}
const resolved = (vars: Vars) => Object.fromEntries(Object.entries(vars).map(([k, v]) => [k, resolve(vars, v)]));
const P = resolved(paper);
const N = resolved(night);

const num = (s: string | undefined) => Number.parseFloat(s ?? "0");
const pick = (r: Vars, keys: string[]) => Object.fromEntries(keys.map((k) => [k, r[k]!]));
const semantic = ["canvas", "surface-raised", "surface-sunken", "ink", "ink-secondary", "ink-tertiary", "hairline", "accent", "accent-text", "accent-glow", "status-ready", "status-working", "status-attention", "glass-fill", "glass-edge", "text-on-ink", "chrome-hi", "chrome-mid", "chrome-lo"];

const ts = `// GENERATED by packages/ui/scripts/gen-tokens.ts from design/tokens/*.css — do not edit.
export const colors = {
  paper: ${JSON.stringify(pick(P, semantic), null, 2).replace(/\n/g, "\n  ")},
  night: ${JSON.stringify(pick(N, semantic), null, 2).replace(/\n/g, "\n  ")},
} as const;
export type ThemeName = keyof typeof colors;
export type ColorToken = keyof typeof colors.paper;

export const space = ${JSON.stringify(Object.fromEntries(Object.keys(P).filter((k) => k.startsWith("space-")).map((k) => [k.slice(6), num(P[k])])))} as const;
export const radius = ${JSON.stringify({ chip: num(P["radius-chip"]), menuItem: num(P["radius-menu-item"]), glass: num(P["radius-glass"]), lens: num(P["radius-lens"]), pill: 999 })} as const;
export const layout = ${JSON.stringify({ hitMin: num(P["hit-min"]), iconSize: num(P["icon-size"]), iconStroke: num(P["icon-stroke"]), statusDot: num(P["status-dot"]) })} as const;

export const type = {
${["display", "title", "heading", "body", "ui", "menu", "meta", "caption"]
  .map((t) => `  ${t}: { fontSize: ${num(P[`type-${t}-size`])}, lineHeight: ${num(P[`type-${t}-line`])}, fontWeight: "${P[`type-${t}-weight`]}" as const${t === "display" ? `, letterSpacing: ${num(P["type-display-tracking"]) * num(P["type-display-size"])}` : ""} },`)
  .join("\n")}
  timecode: { fontSize: ${num(P["type-timecode-size"])}, lineHeight: ${num(P["type-timecode-line"])}, fontWeight: "400" as const },
} as const;

export const fonts = { sans: "Geist", mono: "GeistMono", hand: "Caveat" } as const;

export const motion = {
  morphMs: ${num(P["dur-morph"])},
  hoverMs: ${num(P["dur-hover"])},
  recedeMs: ${num(P["dur-recede"])},
  shimmerMs: ${num(P["dur-shimmer"]) * 1000},
  hoverLift: ${num(P["hover-lift"])},
  recedeBlur: ${num(P["recede-blur"])},
  recedeOpacity: ${num(P["recede-opacity"])},
  /** RN spring approximating --spring-morph (~450ms, slight overshoot) */
  springMorph: { damping: 14, stiffness: 180, mass: 1 },
  springSoft: { damping: 20, stiffness: 160, mass: 1 },
  springPop: { damping: 10, stiffness: 260, mass: 0.8 },
  pressScale: 0.96,
  pressScaleRound: 0.92,
} as const;

export const ambientStrength = { paper: ${num(P["ambient-strength"])}, night: ${num(N["ambient-strength"])} } as const;
`;

const lit = (k: string) => P[k]!;
const theme = `/* GENERATED by packages/ui/scripts/gen-tokens.ts — Tailwind v4 theme. Themed values point at the
   design-system variables (which flip under [data-theme="night"]); fixed values are literal. */
@theme inline {
${semantic.map((k) => `  --color-${k}: var(--${k});`).join("\n")}
  --font-sans: ${lit("font-sans")};
  --font-mono: ${lit("font-mono")};
  --font-hand: ${lit("font-hand")};
${Object.keys(P).filter((k) => k.startsWith("radius-")).map((k) => `  --radius-${k.slice(7)}: ${lit(k)};`).join("\n")}
${Object.keys(P).filter((k) => k.startsWith("space-")).map((k) => `  --spacing-${k.slice(6)}: ${lit(k)};`).join("\n")}
  --shadow-lens: var(--shadow-lens-rest);
  --shadow-lens-hover: var(--shadow-lens-lift);
  --shadow-glass-panel: var(--shadow-glass);
  --shadow-glass-pop: var(--shadow-glass-float);
${["display", "title", "heading", "body", "ui", "menu", "meta", "caption", "timecode"].map((t) => `  --text-${t}: ${lit(`type-${t}-size`)};\n  --text-${t}--line-height: ${lit(`type-${t}-line`)};`).join("\n")}
}
`;

// web: the design CSS verbatim, minus @font-face (fonts come from the geist / @fontsource packages)
const tokensCss = `/* GENERATED from design/tokens/*.css — do not edit. Fonts are loaded by the app (geist, @fontsource/caveat). */\n` +
  files.filter((f) => f !== "fonts.css").map((f) => `/* ${f} */\n${css[f]}`).join("\n");

writeFileSync(new URL("../src/tokens.generated.ts", import.meta.url), ts);
writeFileSync(new URL("../src/theme.css", import.meta.url), theme);
writeFileSync(new URL("../src/tokens.css", import.meta.url), tokensCss);
console.log(`tokens: ${Object.keys(P).length} vars (paper), ${Object.keys(nightOverrides).length} night overrides`);

// component CSS verbatim (scenes + components), and icon path data from the design's Icon.jsx
const comp = new URL("../../../design/components/", import.meta.url);
writeFileSync(
  new URL("../src/components.css", import.meta.url),
  `/* GENERATED from design/components/{footage/scenes.css,eyelore.css} — do not edit. */\n` +
    readFileSync(new URL("footage/scenes.css", comp), "utf8") + "\n" + readFileSync(new URL("eyelore.css", comp), "utf8"),
);
const iconSrc = readFileSync(new URL("icons/Icon.jsx", comp), "utf8");
const m = /const PATHS = (\{[\s\S]*?\n\});/.exec(iconSrc);
if (!m) throw new Error("could not find PATHS in design/components/icons/Icon.jsx");
const paths = JSON.parse(m[1]!.replace(/,\s*}$/, "}")) as Record<string, string>;
writeFileSync(
  new URL("../src/icons.generated.ts", import.meta.url),
  `// GENERATED from design/components/icons/Icon.jsx (Lucide path data, ISC licence) — do not edit.\nexport const ICON_PATHS = ${JSON.stringify(paths, null, 1)} as const;\nexport type IconName = keyof typeof ICON_PATHS;\n`,
);
console.log(`icons: ${Object.keys(paths).length}`);
