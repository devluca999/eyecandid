/**
 * Generate tokens from the Claude Design export (design/system-v2/tokens/*.css). Never hand-edit the outputs.
 *   src/tokens.css            → the v2 token CSS verbatim, then scripts/compat.css (v1 names the editor still reads)
 *   src/theme.css             → Tailwind v4 @theme mapping utilities onto the CSS variables
 *   src/tokens.generated.ts   → resolved values for React Native (Paper + Night), and for tests
 * Fonts come from the geist / @fontsource packages, so fonts.css is not copied. base.css (global element rules and
 * keyframes) is not imported either: it would restyle the editor.
 */
import { existsSync, readFileSync, writeFileSync as writeAlways } from "node:fs";

/**
 * Only touch a generated file when its content changes. Turbo runs this build next to this package's own
 * typecheck, and a rewrite truncates the file for a moment: tsc then read an empty icons.generated.ts
 * ("is not a module") and CI failed at random.
 */
function writeFileSync(target: URL, content: string) {
  if (existsSync(target) && readFileSync(target, "utf8") === content) return;
  writeAlways(target, content);
}

const root = new URL("../../../design/system-v2/tokens/", import.meta.url);
const files = ["colors.css", "typography.css", "spacing.css", "effects.css"];
const css = Object.fromEntries(files.map((f) => [f, readFileSync(new URL(f, root), "utf8")]));
const compatCss = readFileSync(new URL("./compat.css", import.meta.url), "utf8");

type Vars = Record<string, string>;
function block(src: string, selector: string): Vars {
  const out: Vars = {};
  const re = new RegExp(`${selector.replace(/[[\]"=]/g, "\\$&")}\\s*\\{([^}]*)\\}`, "g");
  for (const m of src.matchAll(re)) {
    const body = m[1]!.replace(/\/\*[\s\S]*?\*\//g, "");
    for (const d of body.split(";")) {
      const i = d.indexOf(":");
      if (i < 0) continue;
      const k = d.slice(0, i).trim();
      if (k.startsWith("--")) out[k.slice(2)] = d.slice(i + 1).trim();
    }
  }
  return out;
}

const v2 = Object.values(css).join("\n");
const v2Paper = block(v2, ":root");
const v2Night = block(v2, '[data-theme="night"]');
const compatPaper = block(compatCss, ":root");
const compatNight = block(compatCss, '[data-theme="night"]');
const clash = Object.keys({ ...compatPaper, ...compatNight }).filter((k) => k in v2Paper || k in v2Night);
if (clash.length) throw new Error(`scripts/compat.css redefines system-v2 tokens (v2 wins; drop them from compat): ${clash.join(", ")}`);
const paper: Vars = { ...compatPaper, ...v2Paper };
const nightOverrides: Vars = { ...compatNight, ...v2Night };
const night: Vars = { ...paper, ...nightOverrides };

function resolve(vars: Vars, v: string, depth = 0): string {
  if (depth > 10) return v;
  return v.replace(/var\(--([\w-]+)\)/g, (_, k: string) => (vars[k] !== undefined ? resolve(vars, vars[k]!, depth + 1) : `var(--${k})`));
}
const resolved = (vars: Vars) => Object.fromEntries(Object.entries(vars).map(([k, v]) => [k, resolve(vars, v)]));
const P = resolved(paper);
const N = resolved(night);

/** The first number in a token ("12px", "blur(12px)", "450ms", ".4"). Throws rather than emit 0 or NaN. */
function num(r: Vars, k: string): number {
  const m = /-?\d*\.?\d+/.exec(r[k] ?? "");
  if (!m) throw new Error(`token --${k} is missing or not numeric: ${r[k]}`);
  return Number.parseFloat(m[0]);
}
/** "500 56px/60px var(--font-sans)" → weight, size, line */
function font(r: Vars, k: string) {
  const m = /^(\d{3})\s+(\d+(?:\.\d+)?)px\/(\d+(?:\.\d+)?)px\b/.exec((r[k] ?? "").trim());
  if (!m) throw new Error(`token --${k} is not a "weight size/line" font shorthand: ${r[k]}`);
  return { weight: m[1]!, size: Number(m[2]), line: Number(m[3]) };
}
const lit = (k: string) => {
  if (P[k] === undefined) throw new Error(`token --${k} is missing`);
  return P[k]!;
};
const pick = (r: Vars, keys: string[]) =>
  Object.fromEntries(
    keys.map((k) => {
      if (!r[k] || r[k]!.includes("var(")) throw new Error(`colour token --${k} is missing or unresolved: ${r[k]}`);
      return [k, r[k]!];
    }),
  );
